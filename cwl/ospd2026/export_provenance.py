"""Export CWLProv plus annotations once; preserve subsequent manual profile edits."""
import json
from pathlib import Path
from rdflib import Graph, Namespace, RDF, RDFS

root = Path(__file__).resolve().parents[1]
output = root / "ospd2026/provenance.jsonld"
if output.exists():
    raise SystemExit("provenance.jsonld already exists; preserved its manual edits. Move it aside to regenerate.")
prov = Namespace("http://www.w3.org/ns/prov#")
wf = Namespace("http://purl.org/wf4ever/wfprov#")
schema = Namespace("https://schema.org/")
dct = Namespace("http://purl.org/dc/terms/")
source = Graph().parse(root / "provenance/metadata/provenance/primary.cwlprov.ttl")
notes = Graph().parse(root / "ospd2026/annotations.ttl")
export = Graph()
runs = set(source.subjects(RDF.type, wf.WorkflowRun)) | set(source.subjects(RDF.type, wf.ProcessRun))

# RDFLib copies each run and its attached usage/start/end records.
for run in runs:
    export += source.cbd(run)
    for cluster in notes.objects(run, schema.subjectOf):
        for term in notes.objects(cluster, dct.type):
            export.add((run, RDF.type, term))

entities = set(export.objects(None, prov.entity))
for entity, event in source.subject_objects(prov.qualifiedGeneration):
    if source.value(event, prov.activity) in runs:
        entities.add(entity)
        export.add((entity, prov.qualifiedGeneration, event))
        export += source.cbd(event)

# Copy parameter values only; omit file contents, locations and payload hashes.
private = {source.value(event, prov.entity) for event, role in source.subject_objects(prov.hadRole)
           if str(role).endswith("/credentials_file")}
for entity in entities - private:
    export.add((entity, RDF.type, prov.Entity))
    for member in [entity, *source.objects(entity, prov.hadMember)]:
        if (value := source.value(member, prov.value)) is not None:
            export.add((member, prov.value, value))
            if member != entity:
                export.add((entity, prov.hadMember, member))

export += notes
text = export.serialize(format="json-ld",
                       context={"prov": str(prov), "wfprov": str(wf), "schema": str(schema), "dct": str(dct), "rdfs": str(RDFS)})
document = {"@id": output.name, "rdfs:comment": "Generated by export_provenance.py from CWLProv and annotations.ttl.", **json.loads(text)}
text = json.dumps(document, indent=2) + "\n"
output.write_text(text.replace(output.parent.as_uri() + "/", "").replace(root.as_uri() + "/", "../"))
print(output)
